const LANGUAGE_KEY = 'homepage-studio-language';
let language = 'zh';
try { language = localStorage.getItem(LANGUAGE_KEY) === 'en' ? 'en' : 'zh'; } catch {}
function t(key, params = {}) {
  const template = messages[key]?.[language === 'en' ? 1 : 0] || key;
  return template.replace(/\{(\w+)\}/g, (_, name) => String(params[name] ?? ''));
}
function uiError(key, params = {}) { const error = new Error(t(key, params)); error.uiKey = key; error.uiParams = params; return error; }
function errorText(error) { return error.uiKey ? t(error.uiKey, error.uiParams) : error.message; }
function applyLanguage() {
  document.documentElement.lang = language === 'en' ? 'en' : 'zh-CN';
  document.title = t('studio') + ' · Fan Chen';
  document.querySelectorAll('[data-i18n]').forEach(node => { node.textContent = t(node.dataset.i18n); });
  document.querySelectorAll('[data-i18n-title]').forEach(node => { node.title = t(node.dataset.i18nTitle); });
  document.querySelectorAll('[data-i18n-label]').forEach(node => { node.setAttribute('aria-label', t(node.dataset.i18nLabel)); });
  document.querySelector('#language').value = language;
}
